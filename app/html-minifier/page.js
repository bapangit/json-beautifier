/*
 * Elements that never get a closing tag, used by the
 * tag-matching sanity check below.
 */
const VOID_ELEMENTS = new Set([
  "area",
  "base",
  "br",
  "col",
  "embed",
  "hr",
  "img",
  "input",
  "link",
  "meta",
  "param",
  "source",
  "track",
  "wbr",
]);

/*
 * Elements whose inner content must never be touched by
 * whitespace collapsing — script/style bodies can be
 * whitespace-sensitive (template literals, etc.) and
 * pre/textarea are whitespace-significant by spec.
 */
const RAW_TEXT_ELEMENTS = ["script", "style", "pre", "textarea"];

/*
 * Lightweight, dependency-free HTML minifier.
 *
 * 1. Pulls out <script>/<style>/<pre>/<textarea> blocks so
 *    their contents are never touched by whitespace collapsing.
 * 2. Strips HTML comments (keeping IE conditional comments,
 *    which are still meaningful).
 * 3. Collapses all remaining whitespace runs to a single space,
 *    then removes whitespace sitting directly between tags.
 * 4. Restores the protected blocks, lightly trimming blank
 *    lines inside them without rewriting their content.
 */
function minifyHtmlString(html) {
  const placeholders = [];
  let working = html;

  const rawPattern = new RegExp(
    `<(${RAW_TEXT_ELEMENTS.join("|")})([^>]*)>([\\s\\S]*?)<\\/\\1\\s*>`,
    "gi"
  );

  working = working.replace(rawPattern, (match) => {
    const token = `@@RAW_BLOCK_${placeholders.length}@@`;
    placeholders.push(match);
    return token;
  });

  // Strip comments, but keep IE conditional comments intact.
  working = working.replace(/<!--[\s\S]*?-->/g, (match) =>
    /^<!--\s*\[if/i.test(match) || /<!\[endif\]\s*-->$/i.test(match)
      ? match
      : ""
  );

  // Collapse whitespace runs, then remove it between tag boundaries.
  working = working.replace(/\s+/g, " ");
  working = working.replace(/>\s+</g, "><");
  working = working.trim();

  working = working.replace(/@@RAW_BLOCK_(\d+)@@/g, (_, idx) => {
    const block = placeholders[Number(idx)];

    return block
      .replace(/[ \t]+\n/g, "\n")
      .replace(/\n{2,}/g, "\n")
      .trim();
  });

  return working;
}

/*
 * Read the saved theme synchronously (client only).
 * Used as the useState initializer so there is no
 * "light, then flip to dark" render in between.
 */
function getStoredIsDark() {
  if (typeof window === "undefined") return false;

  try {
    return localStorage.getItem(THEME_STORAGE_KEY) === "dark";
  } catch {
    return false;
  }
}

